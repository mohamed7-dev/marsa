#!/usr/bin/env node
// Sanity checks on the compiled CSS: parses it with lightningcss (strict) and
// fails on parse errors or leftover GTK-isms.
import { transform } from 'lightningcss';
import fs from 'node:fs';
import postcss from 'postcss';

const tokensFile = new URL('../src/styles/tokens.css', import.meta.url);
const tokensCode = fs.readFileSync(tokensFile);
const commonFile = new URL('../src/styles/common.css', import.meta.url);
const commonCode = fs.readFileSync(commonFile);
const componentsDirectory = new URL('../src/styles/components/', import.meta.url);
const widgetsDirectory = new URL('../src/design-system/widgets/', import.meta.url);
const layoutDirectory = new URL('../src/design-system/layout/', import.meta.url);
let failed = false;

for (const [filename, code] of [
    ['tokens.css', tokensCode],
    ['common.css', commonCode],
]) {
    const { warnings } = transform({ filename, code, errorRecovery: true, minify: false });
    for (const warning of warnings) {
        failed = true;
        console.error(`parse warning: ${warning.message} (line ${warning.loc.line})`);
    }

    const text = code.toString();
    const leftovers = [
        /-gtk-/,
        /@define-color/,
        /\.adw-adw-/,
        /(^|[\s,>+~(])(headerbar|toolbarview|scrolledwindow|menubutton|splitbutton|windowhandle)\b(?![-\w])(?=[^{}]*\{)/m,
    ];
    for (const re of leftovers)
        if (re.test(text)) {
            failed = true;
            console.error(`${filename}: leftover pattern in output: ${re}`);
        }
}

const tokensText = tokensCode.toString();
if (!tokensText.includes('--window-bg-color') || !tokensText.includes('--accent-bg-color')) {
    failed = true;
    console.error('tokens.css is missing theme custom properties');
}
postcss.parse(tokensText).walkDecls(declaration => {
    if (!declaration.prop.startsWith('--') && declaration.prop !== 'color-scheme') {
        failed = true;
        console.error(`tokens.css contains a non-token declaration: ${declaration.prop}`);
    }
});
postcss.parse(tokensText).walkRules(rule => {
    if (!/(^|,)\s*:root\b/.test(rule.selector) && !/\[data-adw-color-scheme=/.test(rule.selector)) {
        failed = true;
        console.error(`tokens.css contains a non-token selector: ${rule.selector}`);
    }
});

const commonText = commonCode.toString();
if (!commonText.includes('.adw-background') || !commonText.includes('.adw-icon-dropshadow')) {
    failed = true;
    console.error('common.css is missing shared libadwaita classes');
}
if (/:root\b/.test(commonText)) {
    failed = true;
    console.error('common.css contains global token selectors');
}
if (
    postcss
        .parse(commonText)
        .nodes.some(
            node =>
                node.type === 'rule' &&
                node.selector.split(',').some(selector => selector.trim().startsWith('.adw-button')),
        )
) {
    failed = true;
    console.error('common.css contains widget-specific button rules');
}
postcss.parse(commonText).walkDecls(declaration => {
    if (
        declaration.prop.startsWith('--') &&
        declaration.parent?.type === 'rule' &&
        /:root\b/.test(declaration.parent.selector)
    ) {
        failed = true;
        console.error(`common.css contains a global custom property: ${declaration.prop}`);
    }
});

const expectedComponentStyles = [
    ...fs
        .readdirSync(widgetsDirectory)
        .filter(file => file.startsWith('_') && file.endsWith('.scss'))
        .map(file => `${file.slice(1, -5)}.styles.ts`),
    ...fs
        .readdirSync(layoutDirectory)
        .filter(
            file =>
                file.startsWith('_') &&
                file.endsWith('.scss') &&
                !['_base.scss', '_layouts.scss'].includes(file),
        )
        .map(file => `layout-${file.slice(1, -5)}.styles.ts`),
].sort();
const generatedComponentStyles = fs
    .readdirSync(componentsDirectory)
    .filter(file => file.endsWith('.styles.ts'))
    .sort();
if (JSON.stringify(generatedComponentStyles) !== JSON.stringify(expectedComponentStyles)) {
    failed = true;
    console.error('src/styles/components does not contain one generated style module per widget and layout');
}

for (const filename of generatedComponentStyles) {
    const module = fs.readFileSync(new URL(filename, componentsDirectory), 'utf8');
    const encodedCss = module.match(/unsafeCSS\(("(?:\\.|[^"\\])*")\)/)?.[1];
    if (!module.startsWith('// Generated by scripts/build.mjs.') || !encodedCss) {
        failed = true;
        console.error(`${filename}: invalid generated Lit style module`);
        continue;
    }

    const css = Buffer.from(JSON.parse(encodedCss));
    const { warnings } = transform({
        filename,
        code: css,
        errorRecovery: true,
        minify: false,
    });
    for (const warning of warnings) {
        failed = true;
        console.error(`${filename}: parse warning: ${warning.message} (line ${warning.loc.line})`);
    }
    if (/:root\b/.test(css.toString())) {
        failed = true;
        console.error(`${filename}: component styles contain a global token selector`);
    }
}

console.log(
    failed
        ? 'FAILED'
        : `ok: src/styles/tokens.css, src/styles/common.css, and ${generatedComponentStyles.length} component style modules`,
);
process.exit(failed ? 1 : 0);
